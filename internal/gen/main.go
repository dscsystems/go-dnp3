package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"strings"
)

func bytesReader(b []byte) io.Reader { return bytes.NewReader(b) }

func main() {
	specPath := flag.String("spec", "objects/spec/dnp3_objects.yaml", "path to the object spec")
	root := flag.String("root", ".", "module root to write generated files into")
	flag.Parse()

	if err := run(*specPath, *root); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(specPath, root string) error {
	spec, err := loadSpec(filepath.Join(root, specPath))
	if err != nil {
		return err
	}

	outputs := []struct {
		path string
		emit func(*bytes.Buffer, *Spec)
	}{
		{filepath.Join(root, "objects", "zz_generated_descriptors.go"), emitDescriptors},
		{filepath.Join(root, "objects", "zz_generated_codecs.go"), emitCodecs},
		{filepath.Join(root, "internal", "app", "zz_generated_sizes.go"), emitSizes},
	}

	for _, o := range outputs {
		var buf bytes.Buffer
		o.emit(&buf, spec)

		src, err := format.Source(buf.Bytes())
		if err != nil {
			// Write the unformatted output so the syntax error is inspectable
			// rather than only reported.
			_ = os.WriteFile(o.path+".broken", buf.Bytes(), 0o644)
			return fmt.Errorf("%s: generated code does not parse (unformatted output in %s.broken): %w",
				o.path, o.path, err)
		}
		if err := os.WriteFile(o.path, src, 0o644); err != nil {
			return err
		}
		fmt.Printf("gen: wrote %s (%d objects)\n", o.path, len(spec.Objects))
	}
	return nil
}

const header = `// Code generated by internal/gen from objects/spec/dnp3_objects.yaml. DO NOT EDIT.

`

// ---------------------------------------------------------------- descriptors

func emitDescriptors(b *bytes.Buffer, s *Spec) {
	b.WriteString(header)
	b.WriteString("package objects\n\n")
	b.WriteString(`import "github.com/dscsystems/go-dnp3"` + "\n\n")

	b.WriteString("// descriptors is every group and variation the spec defines.\n")
	b.WriteString("var descriptors = map[GroupVar]Descriptor{\n")
	for _, o := range s.Objects {
		if o.Variable || o.LengthIsV {
			continue // these are rules, not rows; see SizeBits
		}
		bits, _ := o.SizeBits()
		_, hasFlags := o.flagsField()
		_, hasAbs := o.absTimeField()
		_, hasRel := o.relTimeField()

		fmt.Fprintf(b, "\tGV(%d, %d): {\n", o.Group, o.Variation)
		fmt.Fprintf(b, "\t\tGV: GV(%d, %d),\n", o.Group, o.Variation)
		fmt.Fprintf(b, "\t\tName: %q,\n", o.Name)
		fmt.Fprintf(b, "\t\tLevel: %d,\n", o.Level)
		fmt.Fprintf(b, "\t\tKind: %s,\n", validKinds[o.Kind])
		fmt.Fprintf(b, "\t\tMeasurement: %s,\n", pointTypeConst(o.Measure))
		fmt.Fprintf(b, "\t\tSizeBits: %d,\n", bits)
		if o.Packed > 0 {
			fmt.Fprintf(b, "\t\tPacked: true,\n")
		}
		if hasFlags {
			fmt.Fprintf(b, "\t\tHasFlags: true,\n")
		}
		if hasAbs || hasRel {
			fmt.Fprintf(b, "\t\tHasTime: true,\n")
		}
		if hasRel {
			fmt.Fprintf(b, "\t\tRelativeTime: true,\n")
		}
		if vf, _, ok := o.valueField(); ok {
			fmt.Fprintf(b, "\t\tValueBits: %d,\n", fieldBits[vf.Type])
			if vf.Type == "f32" || vf.Type == "f64" {
				fmt.Fprintf(b, "\t\tFloatValue: true,\n")
			}
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	// Groups whose variation is their length, and groups whose size is only
	// knowable from a size prefix on the wire.
	b.WriteString("// lengthIsVariationGroups carry their octet length in the variation\n")
	b.WriteString("// number, so a range of them needs no size table entry.\n")
	b.WriteString("var lengthIsVariationGroups = map[uint8]bool{\n")
	for _, o := range s.Objects {
		if o.LengthIsV {
			fmt.Fprintf(b, "\t%d: true, // %s\n", o.Group, o.Name)
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("// variableGroups are genuinely variable-length. Their encodings carry an\n")
	b.WriteString("// explicit size, so a parser walks them instead of looking them up.\n")
	b.WriteString("var variableGroups = map[uint8]bool{\n")
	for _, o := range s.Objects {
		if o.Variable {
			fmt.Fprintf(b, "\t%d: true, // %s\n", o.Group, o.Name)
		}
	}
	b.WriteString("}\n")

	// Silence the import when no descriptor references dnp3.
	b.WriteString("\nvar _ = dnp3.TypeUnknown\n")
}

func pointTypeConst(measure string) string {
	name := validMeasurements[measure]
	if name == "" {
		return "dnp3.TypeUnknown"
	}
	return "dnp3.Type" + name
}

// ---------------------------------------------------------------------- sizes

func emitSizes(b *bytes.Buffer, s *Spec) {
	b.WriteString(header)
	b.WriteString("package app\n\n")

	b.WriteString(`// generatedSizes maps a group and variation to the encoded size of one
// object in bits. Sizes under eight bits are bit-packed across a range.
var generatedSizes = map[uint16]int{
`)
	for _, o := range s.Objects {
		if o.Variable || o.LengthIsV {
			continue
		}
		bits, _ := o.SizeBits()
		fmt.Fprintf(b, "\tgv(%d, %d): %d, // %s\n", o.Group, o.Variation, bits, o.Name)
	}
	b.WriteString("}\n\n")

	b.WriteString("// lengthIsVariationGroups carry their octet length in the variation number.\n")
	b.WriteString("var lengthIsVariationGroups = map[uint8]bool{\n")
	for _, o := range s.Objects {
		if o.LengthIsV {
			fmt.Fprintf(b, "\t%d: true, // %s\n", o.Group, o.Name)
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("// variableGroups have no fixed size; their encoding carries one.\n")
	b.WriteString("var variableGroups = map[uint8]bool{\n")
	for _, o := range s.Objects {
		if o.Variable {
			fmt.Fprintf(b, "\t%d: true, // %s\n", o.Group, o.Name)
		}
	}
	b.WriteString("}\n")
}

// --------------------------------------------------------------------- codecs

func emitCodecs(b *bytes.Buffer, s *Spec) {
	b.WriteString(header)
	b.WriteString("package objects\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"encoding/binary\"\n")
	b.WriteString("\t\"math\"\n\n")
	b.WriteString("\t\"github.com/dscsystems/go-dnp3\"\n")
	b.WriteString(")\n\n")

	// Keep every import referenced regardless of which variations the spec
	// happens to contain, so trimming the spec cannot break the build.
	b.WriteString("var (\n")
	b.WriteString("\t_ = binary.LittleEndian\n")
	b.WriteString("\t_ = math.Float64bits\n")
	b.WriteString("\t_ = dnp3.Online\n")
	b.WriteString(")\n\n")

	byMeasure := map[string][]Object{}
	for _, o := range s.Objects {
		if o.IsMeasurement() {
			byMeasure[o.Measure] = append(byMeasure[o.Measure], o)
		}
	}

	for _, m := range []string{"binary", "doublebit", "counter", "frozencounter",
		"analog", "binaryoutput", "analogoutput"} {
		objs := byMeasure[m]
		if len(objs) == 0 {
			continue
		}
		goType := "dnp3." + validMeasurements[m]

		fmt.Fprintf(b, "// ---- %s ----\n\n", goType)
		for _, o := range objs {
			emitParse(b, o, goType)
			emitWrite(b, o, goType)
		}

		fmt.Fprintf(b, "var %sCodecs = map[GroupVar]Codec[%s]{\n", m, goType)
		for _, o := range objs {
			fmt.Fprintf(b, "\tGV(%d, %d): {Parse: parse%s, Write: write%s},\n",
				o.Group, o.Variation, o.GoName(), o.GoName())
		}
		b.WriteString("}\n\n")
	}
}

// emitParse writes the decoder for one variation.
func emitParse(b *bytes.Buffer, o Object, goType string) {
	bits, _ := o.SizeBits()
	fmt.Fprintf(b, "// parse%s decodes g%dv%d, %s.\n", o.GoName(), o.Group, o.Variation, o.Name)
	fmt.Fprintf(b, "func parse%s(buf []byte, ctx Context) %s {\n", o.GoName(), goType)
	fmt.Fprintf(b, "\tvar v %s\n", goType)
	fmt.Fprintf(b, "\t_ = buf[%d] // bounds check once, then index freely\n", bits/8-1)

	// Flags, and the state the binary measurements carry inside them.
	if f, ok := o.flagsField(); ok {
		off := o.offsetOf(f.Name)
		fmt.Fprintf(b, "\tv.Flags = dnp3.Flags(buf[%d])\n", off)
		switch o.Measure {
		case "binary", "binaryoutput":
			fmt.Fprintf(b, "\tv.Value = buf[%d]&0x80 != 0\n", off)
		case "doublebit":
			fmt.Fprintf(b, "\tv.Value = dnp3.DoubleBit(buf[%d] >> 6)\n", off)
		}
	} else {
		// A no-flag variation carries no quality information at all. Reporting
		// it as online matches what every other implementation does and is the
		// only reading that lets the value be used; the alternative would mark
		// perfectly good data as offline.
		b.WriteString("\tv.Flags = dnp3.Online\n")
	}

	// Numeric value.
	if f, off, ok := o.valueField(); ok {
		fmt.Fprintf(b, "\tv.Value = %s\n", readExpr(f.Type, off, o.Measure))
	}

	// Time.
	if f, ok := o.absTimeField(); ok {
		off := o.offsetOf(f.Name)
		fmt.Fprintf(b, "\tv.Time = dnp3.Timestamp{Time: dnp3.DNP3ToTime(%s), Quality: ctx.TimeQuality()}\n",
			readTime48(off))
	} else if f, ok := o.relTimeField(); ok {
		off := o.offsetOf(f.Name)
		b.WriteString("\t// A relative-time event is an offset from the common time of\n")
		b.WriteString("\t// occurrence in a preceding group 51 object. Without one the\n")
		b.WriteString("\t// offset is meaningless, so the timestamp is left invalid\n")
		b.WriteString("\t// rather than being anchored to the epoch.\n")
		fmt.Fprintf(b, "\tv.Time = ctx.RelativeTime(uint16(binary.LittleEndian.Uint16(buf[%d:%d])))\n", off, off+2)
	}

	b.WriteString("\treturn v\n}\n\n")
}

// emitWrite writes the encoder for one variation.
func emitWrite(b *bytes.Buffer, o Object, goType string) {
	fmt.Fprintf(b, "// write%s encodes g%dv%d, %s.\n", o.GoName(), o.Group, o.Variation, o.Name)
	fmt.Fprintf(b, "func write%s(dst []byte, v %s, ctx Context) []byte {\n", o.GoName(), goType)
	b.WriteString("\t_ = ctx\n")

	for _, f := range o.Fields {
		switch f.Type {
		case "flags":
			switch o.Measure {
			case "binary", "binaryoutput":
				b.WriteString("\tflags := v.Flags &^ dnp3.StateBit\n")
				b.WriteString("\tif v.Value {\n\t\tflags |= dnp3.StateBit\n\t}\n")
				b.WriteString("\tdst = append(dst, byte(flags))\n")
			case "doublebit":
				b.WriteString("\tdst = append(dst, byte(v.Flags&0x3F)|byte(v.Value&0x03)<<6)\n")
			default:
				b.WriteString("\tdst = append(dst, byte(v.Flags))\n")
			}
		case "time48":
			b.WriteString("\tdst = appendTime48(dst, dnp3.TimeToDNP3(v.Time.Time))\n")
		case "time16":
			// A relative-time event encodes an offset from the context's
			// common time of occurrence, so the writer needs the same context
			// the reader does.
			b.WriteString("\tdst = binary.LittleEndian.AppendUint16(dst, ctx.RelativeOffset(v.Time))\n")
		default:
			if f.Name == "Value" {
				b.WriteString("\t" + writeExpr(f.Type, o.Measure) + "\n")
			}
		}
	}

	b.WriteString("\treturn dst\n}\n\n")
}

// readExpr builds the expression that decodes a numeric value field into the
// measurement's Go type.
func readExpr(typ string, off int, measure string) string {
	toFloat := measure == "analog" || measure == "analogoutput"

	switch typ {
	case "i16":
		e := fmt.Sprintf("int16(binary.LittleEndian.Uint16(buf[%d:%d]))", off, off+2)
		return wrap(e, toFloat, "float64")
	case "u16":
		e := fmt.Sprintf("binary.LittleEndian.Uint16(buf[%d:%d])", off, off+2)
		if toFloat {
			return "float64(" + e + ")"
		}
		return "uint32(" + e + ")"
	case "i32":
		e := fmt.Sprintf("int32(binary.LittleEndian.Uint32(buf[%d:%d]))", off, off+4)
		return wrap(e, toFloat, "float64")
	case "u32":
		e := fmt.Sprintf("binary.LittleEndian.Uint32(buf[%d:%d])", off, off+4)
		if toFloat {
			return "float64(" + e + ")"
		}
		return e
	case "f32":
		return fmt.Sprintf("float64(math.Float32frombits(binary.LittleEndian.Uint32(buf[%d:%d])))", off, off+4)
	case "f64":
		return fmt.Sprintf("math.Float64frombits(binary.LittleEndian.Uint64(buf[%d:%d]))", off, off+8)
	}
	return "0"
}

func wrap(expr string, do bool, as string) string {
	if do {
		return as + "(" + expr + ")"
	}
	return expr
}

// writeExpr builds the statement that encodes a value field.
//
// Narrowing conversions go through the clamp helpers rather than a bare cast:
// converting an out-of-range float64 to an integer is not defined in Go, and
// an analog reading that drifts past a 16-bit point's range would otherwise
// encode as an arbitrary value instead of a saturated one.
func writeExpr(typ, measure string) string {
	fromFloat := measure == "analog" || measure == "analogoutput"

	switch typ {
	case "i16":
		if fromFloat {
			return "dst = binary.LittleEndian.AppendUint16(dst, uint16(clampInt16(v.Value)))"
		}
		return "dst = binary.LittleEndian.AppendUint16(dst, uint16(v.Value))"
	case "u16":
		if fromFloat {
			return "dst = binary.LittleEndian.AppendUint16(dst, clampUint16(v.Value))"
		}
		return "dst = binary.LittleEndian.AppendUint16(dst, uint16(v.Value))"
	case "i32":
		if fromFloat {
			return "dst = binary.LittleEndian.AppendUint32(dst, uint32(clampInt32(v.Value)))"
		}
		return "dst = binary.LittleEndian.AppendUint32(dst, uint32(v.Value))"
	case "u32":
		if fromFloat {
			return "dst = binary.LittleEndian.AppendUint32(dst, clampUint32(v.Value))"
		}
		return "dst = binary.LittleEndian.AppendUint32(dst, uint32(v.Value))"
	case "f32":
		return "dst = binary.LittleEndian.AppendUint32(dst, math.Float32bits(float32(v.Value)))"
	case "f64":
		return "dst = binary.LittleEndian.AppendUint64(dst, math.Float64bits(v.Value))"
	}
	return ""
}

// readTime48 builds the expression that assembles a 48-bit little-endian
// timestamp, which has no encoding/binary helper.
func readTime48(off int) string {
	var parts []string
	for i := range 6 {
		parts = append(parts, fmt.Sprintf("uint64(buf[%d])<<%d", off+i, i*8))
	}
	return strings.Join(parts, "|")
}
